"""Build the Vercel function bundle for the API in a clean directory, and check it.

    python infra/vercel/bundle.py build  OUT [--region cle1]
    python infra/vercel/bundle.py check  OUT [--max-mb 400] [--smoke-db URL]

``build`` copies only what the API imports at runtime (``api/``, ``engine/``,
``worker/`` minus its loop, and the three ``jobs/`` modules the API and engine
use) under ``pkg/``, plus:

* ``app.py``: the entrypoint Vercel loads (an ``app`` FastAPI instance);
* ``pyproject.toml``: the runtime dependencies (``api/requirements.txt`` minus
  uvicorn, which Vercel does not need), Python 3.12, ``tool.vercel.entrypoint``;
* ``vercel.json``: the function region (next to the Neon host) and
  ``maxDuration`` 300 s, Vercel Hobby's ceiling with Fluid compute.

The code sits under ``pkg/`` (not at the top level) because Vercel treats a
top-level ``api/`` directory as file-based functions. Nothing from ``web/``,
``design/``, ``tests/``, ``docs/`` or the model stack of ``jobs/analyse`` goes in.

``check`` installs the dependencies into the bundle's own ``.check/`` folder
(as the Python 3.12 Linux wheels Vercel would use), reports the bundle size
(must stay well under Vercel's 500 MB), times a cold ``import app`` in a fresh
interpreter, and runs the app under an ASGI test client: ``/healthz``,
``/v1/health`` and, with ``--smoke-db``, sign-up and ``GET /v1/events`` against
a real database. It prints sizes, times and status codes only. Standard library
only; the CI job ``vercel-bundle`` and the Deploy workflow both run it.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PYTHON = "3.12"
MAX_DURATION = 300  # seconds; Vercel Hobby's maximum with Fluid compute
DEFAULT_REGION = "iad1"
LIMIT_MB = 500  # Vercel's uncompressed Python bundle limit

# (source relative to ROOT, destination relative to pkg/)
TREES = ["api", "engine"]
FILES = [
    "worker/__init__.py", "worker/passes.py", "worker/sync.py", "worker/scoring.py",
    "jobs/__init__.py", "jobs/codes.py", "jobs/analyse/__init__.py", "jobs/analyse/anomalies.py",
]  # fmt: skip
DATA_TREES = ["jobs/data"]
SKIP = {"__pycache__", "Dockerfile", "README.md", "requirements-dev.txt"}
DROP_REQUIREMENTS = {"uvicorn"}

APP_PY = '''"""Vercel entrypoint, generated by infra/vercel/bundle.py. Do not edit in the bundle."""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "pkg"))

from fastapi import FastAPI  # noqa: E402

from api.main import _app  # noqa: E402

app: FastAPI = _app()
'''


def requirements() -> list[str]:
    out: list[str] = []
    for line in (ROOT / "api/requirements.txt").read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        name = line.split("==")[0].split("[")[0].strip().lower()
        if name not in DROP_REQUIREMENTS:
            out.append(line)
    return out


def _copytree(src: Path, dst: Path) -> None:
    shutil.copytree(src, dst, ignore=lambda d, names: [n for n in names if n in SKIP or n.endswith((".pyc", ".pyo"))])


def build(out: Path, region: str = DEFAULT_REGION) -> Path:
    if out.exists():
        shutil.rmtree(out)
    pkg = out / "pkg"
    pkg.mkdir(parents=True)
    for t in TREES:
        _copytree(ROOT / t, pkg / t)
    for t in DATA_TREES:
        _copytree(ROOT / t, pkg / t)
    for f in FILES:
        (pkg / f).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / f, pkg / f)
    (out / "app.py").write_text(APP_PY)
    deps = ",\n".join(f'    "{r}"' for r in requirements())
    (out / "pyproject.toml").write_text(
        "[project]\n"
        'name = "riskpredict-api"\n'
        'version = "0.0.0"\n'
        f'requires-python = "=={PYTHON}.*"\n'
        f"dependencies = [\n{deps},\n]\n\n"
        "[tool.vercel]\n"
        'entrypoint = "app:app"\n'
    )
    (out / ".python-version").write_text(PYTHON + "\n")
    (out / "vercel.json").write_text(json.dumps({
        "$schema": "https://openapi.vercel.sh/vercel.json",
        "regions": [region],
        "functions": {"app.py": {"maxDuration": MAX_DURATION}},
    }, indent=2) + "\n")  # fmt: skip
    (out / ".vercelignore").write_text(".check/\n__pycache__/\n")
    return out


def file_list(out: Path) -> list[str]:
    return sorted(str(p.relative_to(out)) for p in out.rglob("*") if p.is_file() and ".check" not in p.parts)


def _size(path: Path) -> int:
    return sum(p.stat().st_size for p in path.rglob("*") if p.is_file())


def check(out: Path, max_mb: float = 400.0, smoke_db: str = "") -> dict:
    site = out / ".check" / "site"
    if site.exists():
        shutil.rmtree(site)
    site.mkdir(parents=True)
    cmd = [sys.executable, "-m", "pip", "install", "--quiet", "--disable-pip-version-check", "--no-compile",
           "--target", str(site), "--only-binary=:all:", "--platform", "manylinux2014_x86_64",
           "--platform", "manylinux_2_28_x86_64", "--python-version", PYTHON, "--implementation", "cp",
           *requirements()]  # fmt: skip
    subprocess.run(cmd, check=True)
    code_mb = sum((out / p).stat().st_size for p in file_list(out)) / 1e6
    deps_mb = _size(site) / 1e6
    total = code_mb + deps_mb
    biggest = sorted(((p.name, _size(p) / 1e6) for p in site.iterdir() if p.is_dir() and not p.name.endswith("-info")),
                     key=lambda x: -x[1])[:6]  # fmt: skip
    report = {"code_mb": round(code_mb, 2), "deps_mb": round(deps_mb, 1), "total_mb": round(total, 1),
              "limit_mb": LIMIT_MB, "largest": [f"{n} {m:.0f} MB" for n, m in biggest]}  # fmt: skip
    if total > max_mb:
        raise SystemExit(f"bundle is {total:.0f} MB, over the {max_mb:.0f} MB guard (Vercel's limit is {LIMIT_MB} MB)")
    same_python = f"{sys.version_info.major}.{sys.version_info.minor}" == PYTHON
    if same_python:  # the wheels were picked for 3.12; only a 3.12 interpreter can import them
        report.update(_runtime(out, site, smoke_db))
    else:
        report["runtime"] = f"skipped: this interpreter is not Python {PYTHON}"
    return report


SMOKE = r'''
import json, os, sys, time
t0 = time.perf_counter()
import app
cold = time.perf_counter() - t0
from starlette.testclient import TestClient
out = {"cold_import_s": round(cold, 2)}
with TestClient(app.app, base_url="https://api.example.test") as c:
    out["healthz"] = c.get("/healthz").status_code
    h = c.get("/v1/health")
    out["health"] = h.status_code
    if os.environ.get("SMOKE_DB"):
        import uuid
        r = c.post("/v1/auth/sign-up", json={"email": f"smoke-{uuid.uuid4().hex[:8]}@example.test",
                                             "password": "smoke test password", "workspace_name": "Smoke"})
        out["sign_up"] = r.status_code
        if r.status_code == 201:
            b = r.json()
            hdr = {"Authorization": "Bearer " + b["access_token"], "X-Workspace-Id": b["workspace_id"]}
            out["events"] = c.get("/v1/events", headers=hdr).status_code
            out["schema_version"] = c.get("/v1/health").json().get("schema_version")
t0 = time.perf_counter()
import engine, jobs.analyse.anomalies, sklearn.ensemble  # the first request that scores or runs a what-if pays this once
out["engine_import_s"] = round(time.perf_counter() - t0, 2)
print("SMOKE " + json.dumps(out))
'''


def _runtime(out: Path, site: Path, smoke_db: str) -> dict:
    env = {k: v for k, v in os.environ.items() if not k.startswith(("DATABASE_URL", "PYTHON"))}
    env.update({
        "PYTHONPATH": str(site), "PYTHONDONTWRITEBYTECODE": "1",
        # placeholders: the pool does not connect until a request needs the database
        "DATABASE_URL_APP": smoke_db or "postgresql://nobody@127.0.0.1:9/none",
        "JWT_SIGNING_KEY": "c21va2UtdGVzdC1vbmx5LXNtb2tlLXRlc3Qtb25seS0xMjM0NTY3OA==",
        "SMOKE_DB": "1" if smoke_db else "",
    })  # fmt: skip
    # compile first, as Vercel does at build time, so the import time is a warm-disk cold start
    subprocess.run([sys.executable, "-m", "compileall", "-q", str(out / "pkg"), str(site)], check=False,
                   stdout=subprocess.DEVNULL, env=env)  # fmt: skip
    with tempfile.TemporaryDirectory() as tmp:
        start = time.perf_counter()
        proc = subprocess.run([sys.executable, "-I", "-c", f"import sys; sys.path[:0] = [{str(out)!r}, {str(site)!r}]\n" + SMOKE],
                              cwd=tmp, env=env, capture_output=True, text=True, timeout=300)  # fmt: skip
        wall = time.perf_counter() - start
    line = next((ln for ln in proc.stdout.splitlines() if ln.startswith("SMOKE ")), None)
    if proc.returncode != 0 or line is None:
        lines = [ln for ln in proc.stderr.splitlines() if ln.strip() and set(ln.strip()) - set("^~ ")]
        last = (lines or ["?"])[-1]
        raise SystemExit(f"the bundle did not start under the ASGI test client: {last[:300]}")
    result = json.loads(line[6:])
    result["process_s"] = round(wall, 2)
    bad = {k: v for k, v in result.items() if k in ("healthz", "health", "events") and v != 200}
    if bad or result.get("sign_up", 201) != 201:
        raise SystemExit(f"bundle smoke test failed: {result}")
    return result


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build")
    b.add_argument("out", type=Path)
    b.add_argument("--region", default=DEFAULT_REGION)
    c = sub.add_parser("check")
    c.add_argument("out", type=Path)
    c.add_argument("--max-mb", type=float, default=400.0)
    c.add_argument("--smoke-db", default=os.environ.get("SMOKE_DATABASE_URL", ""))
    args = ap.parse_args(argv)
    if args.cmd == "build":
        build(args.out, args.region)
        files = file_list(args.out)
        print(f"bundle: {len(files)} files in {args.out}")
        return 0
    report = check(args.out, args.max_mb, args.smoke_db)
    for k, v in report.items():
        print(f"{k}: {v}")
    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a", encoding="utf-8") as f:
            f.write("### Vercel function bundle\n\n| | |\n|---|---|\n")
            for k, v in report.items():
                f.write(f"| {k} | {', '.join(v) if isinstance(v, list) else v} |\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
